"""Freeze editable transcript scenarios into an expanded golden benchmark dataset.

This script converts the transcript-first scenario library into versioned benchmark
artifacts that the Phase 4 benchmark runner can evaluate.

Usage:
  uv run python -m scripts.freeze_transcript_scenarios
  uv run python -m scripts.freeze_transcript_scenarios --scenario-ids hs_python_loops_30m,college_stoichiometry_30m
"""

from __future__ import annotations

import argparse
import csv
import json
from copy import deepcopy
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

from app.config import BACKEND_ROOT, REQUIRED_RUBRIC_CRITERIA, RUBRIC_VERSION
from app.models import (
    BenchmarkTranscript,
    DatasetVersion,
    ExpectedMissedOpportunities,
    ExpectedScores,
    GroundTruth,
    MissedOpportunity,
    Scenario,
    Turn,
)
from app.transcript_models import TranscriptScenario, TranscriptTurnDraft
from app.transcript_service import TRANSCRIPT_SCENARIO_ROOT, TranscriptScenarioService

DEFAULT_OUTPUT_ROOT = BACKEND_ROOT / "data" / "golden_benchmark_expanded"
DATASET_VERSION = "golden_benchmark_expanded_v1.1_transcript_scenarios"
CREATED_BY = "researcher_annotation_freeze_script_v1"

STRONG_SCORES = {
    "pck_conceptual_accuracy": 5,
    "scaffolding": 5,
    "formative_assessment": 4,
    "cognitive_questioning": 4,
    "missed_pedagogical_opportunity": 5,
}

WEAK_SCORES = {
    "pck_conceptual_accuracy": 2,
    "scaffolding": 1,
    "formative_assessment": 1,
    "cognitive_questioning": 1,
    "missed_pedagogical_opportunity": 1,
}

CSV_HEADER = [
    "transcript_id",
    "reviewer_id",
    "criterion",
    "human_score",
    "issue_id",
    "evidence_turn_ids",
    "accepted_ground_truth",
    "comment",
    "timestamp",
]


def freeze_transcript_scenarios(
    *,
    output_root: Path = DEFAULT_OUTPUT_ROOT,
    source_root: Path = TRANSCRIPT_SCENARIO_ROOT,
    scenario_ids: list[str] | None = None,
    strict_readiness: bool = True,
) -> dict[str, Any]:
    """Export transcript-system scenarios into golden-benchmark file layout.

    The source transcript is treated as the strong variant. A weak variant is
    generated by replacing selected teacher turns with deliberately under-scaffolded
    responses that ignore or rush past visible misconceptions. This makes the
    expanded benchmark useful for baseline-vs-TIL evaluator comparison while
    preserving deterministic, reproducible input files.
    """

    service = TranscriptScenarioService(root=source_root)
    listing = service.list_scenarios().scenarios
    selected_ids = scenario_ids or [item.scenario_id for item in listing]
    output_root.mkdir(parents=True, exist_ok=True)

    exported: list[dict[str, Any]] = []
    readiness_records: list[dict[str, Any]] = []

    for scenario_id in selected_ids:
        readiness = service.run_readiness_test(scenario_id)
        readiness_record = {
            "scenario_id": scenario_id,
            "passed": readiness.passed,
            "checks": [check.model_dump() for check in readiness.checks],
        }
        readiness_records.append(readiness_record)
        if strict_readiness and not readiness.passed:
            failed = [check.model_dump() for check in readiness.checks if check.status == "fail"]
            raise ValueError(f"Scenario {scenario_id} failed readiness checks: {failed}")

        scenario = service.load_scenario(scenario_id)
        scenario_dir = output_root / _safe_dir_name(scenario.scenario_id)
        scenario_dir.mkdir(parents=True, exist_ok=True)
        _write_json_model(scenario_dir / "scenario.json", _to_benchmark_scenario(scenario))

        strong_transcript = _to_benchmark_transcript(scenario, variant="strong")
        weak_transcript, weak_evidence = _to_weak_benchmark_transcript(scenario)

        _write_variant_files(
            scenario_dir=scenario_dir,
            transcript=strong_transcript,
            scores=STRONG_SCORES,
            score_notes=_strong_score_notes(scenario),
            ground_truth=GroundTruth(
                transcript_id=strong_transcript.transcript_id,
                rubric_version=RUBRIC_VERSION,
                created_by=CREATED_BY,
                review_status="researcher_annotated",
                summary=(
                    "Strong transcript variant: teacher surfaces misconceptions, uses subject-specific modelling, "
                    "scaffolds reasoning, checks understanding, and closes with next-step learning action."
                ),
                known_issues=[],
            ),
            missed=ExpectedMissedOpportunities(
                transcript_id=strong_transcript.transcript_id,
                missed_opportunities=[],
            ),
            annotation_rows=_annotation_rows(
                transcript_id=strong_transcript.transcript_id,
                scores=STRONG_SCORES,
                issue_id="strong_reference",
                evidence_turn_ids=weak_evidence["strong_reference_turn_ids"],
                comment="Researcher annotation: strong/reference teaching pattern for benchmark comparison.",
            ),
        )

        weak_missed = _weak_missed_opportunities(weak_transcript, weak_evidence, scenario)
        _write_variant_files(
            scenario_dir=scenario_dir,
            transcript=weak_transcript,
            scores=WEAK_SCORES,
            score_notes=_weak_score_notes(scenario),
            ground_truth=GroundTruth(
                transcript_id=weak_transcript.transcript_id,
                rubric_version=RUBRIC_VERSION,
                created_by=CREATED_BY,
                review_status="researcher_annotated",
                summary=(
                    "Weak transcript variant: teacher rushes past visible misconceptions, gives generic explanations, "
                    "avoids step-by-step scaffolding, and uses superficial formative checks."
                ),
                known_issues=[
                    "misconception_not_addressed",
                    "low_scaffolding",
                    "weak_formative_assessment",
                    "low_cognitive_questioning",
                    "missed_student_reasoning_signal",
                ],
            ),
            missed=ExpectedMissedOpportunities(
                transcript_id=weak_transcript.transcript_id,
                missed_opportunities=weak_missed,
            ),
            annotation_rows=_annotation_rows(
                transcript_id=weak_transcript.transcript_id,
                scores=WEAK_SCORES,
                issue_id="weak_reference",
                evidence_turn_ids=weak_evidence["missed_core_turn_ids"],
                comment="Researcher annotation: weak teaching pattern with known missed misconception/scaffolding opportunities.",
            ),
        )

        exported.append(
            {
                "scenario_id": scenario.scenario_id,
                "title": scenario.title,
                "subject": scenario.subject,
                "education_level": scenario.education_level,
                "strong_transcript_id": strong_transcript.transcript_id,
                "weak_transcript_id": weak_transcript.transcript_id,
                "turn_count": len(strong_transcript.turns),
                "readiness_passed": readiness.passed,
            }
        )

    dataset = DatasetVersion(
        dataset_version=DATASET_VERSION,
        created_at=datetime.now(timezone.utc).isoformat(),
        description=(
            "Expanded transcript-first benchmark exported from editable 30-minute PixelClass TIL scenarios. "
            "Each scenario contains researcher-annotated strong and weak teaching variants."
        ),
        scenario_count=len(exported),
        transcript_count=len(exported) * 2,
        rubric_version=RUBRIC_VERSION,
    )
    _write_json_model(output_root / "DATASET_VERSION.json", dataset)

    manifest = {
        "dataset_version": DATASET_VERSION,
        "created_at": dataset.created_at,
        "source_root": str(source_root),
        "output_root": str(output_root),
        "scenario_count": len(exported),
        "transcript_count": len(exported) * 2,
        "rubric_criteria": sorted(REQUIRED_RUBRIC_CRITERIA),
        "exported_scenarios": exported,
        "readiness_records": readiness_records,
        "claim_boundary": (
            "Researcher-authored synthetic benchmark transcripts; suitable for controlled evaluator comparison, "
            "not evidence of real classroom learning gains."
        ),
    }
    (output_root / "FREEZE_MANIFEST.json").write_text(
        json.dumps(manifest, indent=2, ensure_ascii=False), encoding="utf-8"
    )
    (output_root / "README.md").write_text(_readme(manifest), encoding="utf-8")
    return manifest


def _to_benchmark_scenario(scenario: TranscriptScenario) -> Scenario:
    return Scenario(
        scenario_id=scenario.scenario_id,
        title=scenario.title,
        domain=scenario.subject,
        education_level=scenario.education_level.replace("_", " "),
        learning_objective="; ".join(scenario.learning_objectives),
        common_misconceptions=scenario.misconception_targets,
        target_concepts=_target_concepts(scenario),
    )


def _target_concepts(scenario: TranscriptScenario) -> list[str]:
    concepts: list[str] = []
    for value in [*scenario.evaluator_focus, *scenario.materials_needed]:
        cleaned = str(value).strip()
        if cleaned and cleaned not in concepts:
            concepts.append(cleaned)
    return concepts[:10]


def _to_benchmark_transcript(scenario: TranscriptScenario, *, variant: str) -> BenchmarkTranscript:
    return BenchmarkTranscript(
        transcript_id=f"{scenario.scenario_id}_{variant}_001",
        scenario_id=scenario.scenario_id,
        variant=variant,  # type: ignore[arg-type]
        domain=scenario.subject,
        education_level=scenario.education_level.replace("_", " "),
        learning_objective="; ".join(scenario.learning_objectives),
        turns=_to_turns(scenario.transcript_turns),
    )


def _to_weak_benchmark_transcript(scenario: TranscriptScenario) -> tuple[BenchmarkTranscript, dict[str, list[str]]]:
    weak_turns = deepcopy(sorted(scenario.transcript_turns, key=lambda item: (item.minute, item.turn_id)))
    replacements = {
        "misconception_response": 0,
        "teacher_explanation": 0,
        "scaffolding": 0,
        "formative_assessment": 0,
        "cognitive_questioning": 0,
        "differentiated_practice": 0,
    }
    weak_markers: dict[str, list[str]] = {
        "missed_core_turn_ids": [],
        "missed_scaffold_turn_ids": [],
        "weak_formative_turn_ids": [],
        "strong_reference_turn_ids": [],
    }

    for turn in weak_turns:
        tags = set(turn.pedagogical_tags)
        if turn.speaker_role != "teacher":
            continue
        if "misconception_response" in tags and replacements["misconception_response"] < 2:
            turn.message = (
                "Let's not spend time unpacking that misconception now. Just memorise the final rule and we will move on."
            )
            turn.pedagogical_tags = ["weak_missed_misconception", "low_evidence_grounding"]
            replacements["misconception_response"] += 1
            weak_markers["missed_core_turn_ids"].append(turn.turn_id)
            continue
        if (
            {"teacher_explanation", "modelling", "worked_example"} & tags
            and replacements["teacher_explanation"] < 2
        ):
            prefix = _part_prefix(turn.message)
            turn.message = (
                f"{prefix} Copy the rule and the final answer from the board. I will skip the reasoning steps today, "
                "so use memorisation rather than evidence from the example."
            )
            turn.pedagogical_tags = ["weak_generic_explanation", "low_conceptual_support"]
            replacements["teacher_explanation"] += 1
            continue
        if (
            {"scaffolding", "low_confidence_support", "procedural_scaffolding"} & tags
            and replacements["scaffolding"] < 2
        ):
            turn.message = (
                "You should be able to follow this without a step-by-step table. Try to keep up with the example."
            )
            turn.pedagogical_tags = ["weak_low_scaffolding", "missed_student_support"]
            replacements["scaffolding"] += 1
            weak_markers["missed_scaffold_turn_ids"].append(turn.turn_id)
            continue
        if (
            {"formative_assessment", "quick_check", "final_review"} & tags
            and replacements["formative_assessment"] < 3
        ):
            turn.message = "Everyone understands, right? Good, we can continue."
            turn.pedagogical_tags = ["weak_superficial_check", "weak_formative_assessment"]
            replacements["formative_assessment"] += 1
            weak_markers["weak_formative_turn_ids"].append(turn.turn_id)
            continue
        if (
            {"teacher_question", "probing_reasoning", "evidence_prompt", "targeted_question"} & tags
            and replacements["cognitive_questioning"] < 2
        ):
            turn.message = "This is straightforward, so I will give the answer rather than asking for reasoning."
            turn.pedagogical_tags = ["weak_low_cognitive_questioning"]
            replacements["cognitive_questioning"] += 1
            continue
        if "differentiated_practice" in tags and replacements["differentiated_practice"] < 1:
            turn.message = "Do the same type of problem silently. I will not check each person's reasoning today."
            turn.pedagogical_tags = ["weak_low_differentiation", "missed_individual_feedback"]
            replacements["differentiated_practice"] += 1
            continue

    strong_reference_ids = _first_turn_ids(
        scenario.transcript_turns,
        preferred_tags=["misconception_event", "misconception_response", "scaffolding", "formative_assessment"],
        limit=4,
    )
    weak_markers["strong_reference_turn_ids"] = strong_reference_ids

    # Include student evidence adjacent to weakened teacher responses so ground truth
    # points at both the learner signal and the missed teacher move.
    weak_markers["missed_core_turn_ids"] = _with_previous_student_turns(
        weak_turns, weak_markers["missed_core_turn_ids"]
    )
    weak_markers["missed_scaffold_turn_ids"] = _with_previous_student_turns(
        weak_turns, weak_markers["missed_scaffold_turn_ids"]
    )
    weak_markers["weak_formative_turn_ids"] = weak_markers["weak_formative_turn_ids"][:3] or _first_turn_ids(
        weak_turns,
        preferred_tags=["weak_superficial_check", "formative_assessment"],
        limit=2,
    )

    transcript = BenchmarkTranscript(
        transcript_id=f"{scenario.scenario_id}_weak_001",
        scenario_id=scenario.scenario_id,
        variant="weak",
        domain=scenario.subject,
        education_level=scenario.education_level.replace("_", " "),
        learning_objective="; ".join(scenario.learning_objectives),
        turns=_to_turns(weak_turns),
    )
    return transcript, weak_markers


def _part_prefix(message: str) -> str:
    """Preserve a lesson-part label when weakening a long teacher explanation."""

    if message.startswith("PART ") and "." in message:
        return message.split(".", 1)[0].strip() + "."
    return "Explanation."


def _to_turns(turns: list[TranscriptTurnDraft]) -> list[Turn]:
    return [
        Turn(
            turn_id=turn.turn_id,
            speaker_role=turn.speaker_role,
            speaker_name=turn.speaker_name,
            message=turn.message,
        )
        for turn in sorted(turns, key=lambda item: (item.minute, item.turn_id))
    ]


def _first_turn_ids(
    turns: list[TranscriptTurnDraft], *, preferred_tags: list[str], limit: int
) -> list[str]:
    ids: list[str] = []
    for turn in sorted(turns, key=lambda item: (item.minute, item.turn_id)):
        if any(tag in turn.pedagogical_tags for tag in preferred_tags):
            ids.append(turn.turn_id)
        if len(ids) >= limit:
            break
    if ids:
        return ids
    return [turn.turn_id for turn in sorted(turns, key=lambda item: (item.minute, item.turn_id))[:limit]]


def _with_previous_student_turns(turns: list[TranscriptTurnDraft], teacher_turn_ids: list[str]) -> list[str]:
    by_id = {turn.turn_id: index for index, turn in enumerate(turns)}
    result: list[str] = []
    for teacher_turn_id in teacher_turn_ids:
        index = by_id.get(teacher_turn_id)
        if index is None:
            continue
        for previous in reversed(turns[:index]):
            if previous.speaker_role == "student":
                if previous.turn_id not in result:
                    result.append(previous.turn_id)
                break
        if teacher_turn_id not in result:
            result.append(teacher_turn_id)
    return result[:4]


def _weak_missed_opportunities(
    transcript: BenchmarkTranscript,
    evidence: dict[str, list[str]],
    scenario: TranscriptScenario,
) -> list[MissedOpportunity]:
    core_ids = evidence["missed_core_turn_ids"] or [transcript.turns[0].turn_id]
    scaffold_ids = evidence["missed_scaffold_turn_ids"] or core_ids
    formative_ids = evidence["weak_formative_turn_ids"] or core_ids
    topic = scenario.subject.lower()
    misconception = scenario.misconception_targets[0] if scenario.misconception_targets else "the visible misconception"
    return [
        MissedOpportunity(
            id="mo_001",
            criterion="missed_pedagogical_opportunity",
            description=f"The teacher does not directly repair the visible {topic} misconception: {misconception}",
            evidence_turn_ids=core_ids,
            expected_action=(
                "Ask the student to explain the misconception, contrast it with the worked example, and state a repaired rule."
            ),
        ),
        MissedOpportunity(
            id="mo_002",
            criterion="missed_pedagogical_opportunity",
            description="The teacher misses a chance to provide step-by-step scaffolding after student uncertainty.",
            evidence_turn_ids=scaffold_ids,
            expected_action=(
                "Use a structured evidence/reasoning table or worked-example trace before asking students to generalise."
            ),
        ),
        MissedOpportunity(
            id="mo_003",
            criterion="missed_pedagogical_opportunity",
            description="The teacher uses a superficial class-wide check instead of verifying student reasoning.",
            evidence_turn_ids=formative_ids,
            expected_action="Use an exit-style prompt requiring each student to justify the answer with evidence.",
        ),
    ]


def _write_variant_files(
    *,
    scenario_dir: Path,
    transcript: BenchmarkTranscript,
    scores: dict[str, int],
    score_notes: dict[str, str],
    ground_truth: GroundTruth,
    missed: ExpectedMissedOpportunities,
    annotation_rows: list[dict[str, str]],
) -> None:
    variant_dir = scenario_dir / transcript.variant
    variant_dir.mkdir(parents=True, exist_ok=True)
    _write_json_model(variant_dir / "transcript.json", transcript)
    _write_json_model(variant_dir / "ground_truth.json", ground_truth)
    _write_json_model(
        variant_dir / "expected_scores.json",
        ExpectedScores(transcript_id=transcript.transcript_id, scores=scores, notes=score_notes),
    )
    _write_json_model(variant_dir / "expected_missed_opportunities.json", missed)
    _write_annotation_csv(variant_dir / "expert_annotation.csv", annotation_rows)


def _annotation_rows(
    *,
    transcript_id: str,
    scores: dict[str, int],
    issue_id: str,
    evidence_turn_ids: list[str],
    comment: str,
) -> list[dict[str, str]]:
    timestamp = datetime.now(timezone.utc).isoformat()
    evidence = ";".join(evidence_turn_ids)
    return [
        {
            "transcript_id": transcript_id,
            "reviewer_id": "researcher_freeze_v1",
            "criterion": criterion,
            "human_score": str(score),
            "issue_id": issue_id,
            "evidence_turn_ids": evidence,
            "accepted_ground_truth": "true",
            "comment": comment,
            "timestamp": timestamp,
        }
        for criterion, score in scores.items()
    ]


def _strong_score_notes(scenario: TranscriptScenario) -> dict[str, str]:
    return {
        "pck_conceptual_accuracy": f"Teacher explains the central {scenario.subject} concept and responds to visible misconception signals.",
        "scaffolding": "Teacher distributes explanation across worked examples, prompts, and stepwise reasoning.",
        "formative_assessment": "Teacher includes quick checks and final review, although full independent assessment remains limited in a transcript MVP.",
        "cognitive_questioning": "Teacher asks prediction, explanation, and transfer questions across the lesson.",
        "missed_pedagogical_opportunity": "No major known missed opportunity is intentionally embedded in the strong/reference variant.",
    }


def _weak_score_notes(scenario: TranscriptScenario) -> dict[str, str]:
    return {
        "pck_conceptual_accuracy": f"Teacher rushes past the target {scenario.subject} misconception instead of explicitly repairing it.",
        "scaffolding": "Teacher avoids step-by-step scaffolding and asks struggling students to keep up.",
        "formative_assessment": "Teacher relies on superficial whole-class checks without checking reasoning.",
        "cognitive_questioning": "Teacher gives answers rather than eliciting prediction, evidence, or explanation.",
        "missed_pedagogical_opportunity": "Multiple learner signals are intentionally missed to create a weak comparison variant.",
    }


def _write_json_model(path: Path, model) -> None:
    path.write_text(model.model_dump_json(indent=2), encoding="utf-8")


def _write_annotation_csv(path: Path, rows: list[dict[str, str]]) -> None:
    with path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=CSV_HEADER)
        writer.writeheader()
        for row in rows:
            writer.writerow(row)


def _safe_dir_name(value: str) -> str:
    return value.replace("/", "_").replace("\\", "_")


def _readme(manifest: dict[str, Any]) -> str:
    lines = [
        "# PixelClass TIL Expanded Golden Benchmark",
        "",
        f"Dataset version: `{manifest['dataset_version']}`",
        "",
        "This folder is generated from the transcript-first scenario library.",
        "Each scenario contains a researcher-authored strong teaching variant and a deliberately weak variant.",
        "",
        "## Claim boundary",
        "",
        manifest["claim_boundary"],
        "",
        "## Included scenarios",
        "",
    ]
    for item in manifest["exported_scenarios"]:
        lines.append(
            f"- `{item['scenario_id']}` — {item['title']} ({item['subject']}, {item['education_level']}); "
            f"strong=`{item['strong_transcript_id']}`, weak=`{item['weak_transcript_id']}`"
        )
    lines.extend(
        [
            "",
            "## Run benchmark",
            "",
            "```bash",
            "cd D:/Code/til-classroom-sim/backend",
            "EVALUATOR_PROVIDER=fallback EVALUATOR_MODEL=deterministic-fallback uv run python -m scripts.run_benchmark --benchmark-root data/golden_benchmark_expanded --conditions baseline,til --repetitions 3",
            "```",
            "",
            "For a real LLM experiment, configure one provider/model in `.env`, keep temperature fixed, and run the same command without overriding the provider to fallback.",
        ]
    )
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--output-root", type=Path, default=DEFAULT_OUTPUT_ROOT)
    parser.add_argument("--source-root", type=Path, default=TRANSCRIPT_SCENARIO_ROOT)
    parser.add_argument("--scenario-ids", default=None, help="Comma-separated scenario IDs; defaults to all scenarios.")
    parser.add_argument("--allow-readiness-warnings", action="store_true")
    args = parser.parse_args()
    ids = [item.strip() for item in args.scenario_ids.split(",") if item.strip()] if args.scenario_ids else None
    manifest = freeze_transcript_scenarios(
        output_root=args.output_root,
        source_root=args.source_root,
        scenario_ids=ids,
        strict_readiness=not args.allow_readiness_warnings,
    )
    print(json.dumps({
        "dataset_version": manifest["dataset_version"],
        "output_root": manifest["output_root"],
        "scenario_count": manifest["scenario_count"],
        "transcript_count": manifest["transcript_count"],
    }, indent=2, ensure_ascii=False))


if __name__ == "__main__":
    main()
